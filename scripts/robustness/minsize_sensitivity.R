suppressMessages({library(fgsea);library(data.table)})
gmt <- readRDS("output/glycan2enzMap_enzyme_grouped.rds")
grp <- as.data.table(readRDS("output/glycomeRes_group.rds"))
lfc <- setNames(grp$logFC,grp$group); lfc<-sort(lfc)
cat("各 pathway の set size:\n"); print(sort(sapply(gmt,length)))
run <- function(ms){ set.seed(1); r<-suppressWarnings(fgsea(gmt,lfc,minSize=ms,maxSize=500,nPermSimple=50000))
  r[,.(pathway,size,NES=round(NES,2),pval=signif(pval,2))][order(pval)] }
m1<-run(1); m2<-run(2); m3<-run(3)
cat("\n=== minSize=1 で検定された pathway 数:",nrow(m1)," / minSize=2:",nrow(m2)," / minSize=3:",nrow(m3),"\n")
cat("\n=== minSize=2 で除外される pathway（size<2）===\n"); print(setdiff(m1$pathway,m2$pathway))
cat("=== minSize=3 で除外 ===\n"); print(setdiff(m1$pathway,m3$pathway))
cmp <- merge(m1[,.(pathway,p_ms1=pval)], m2[,.(pathway,p_ms2=pval)], by="pathway", all=TRUE)
cmp <- merge(cmp, m3[,.(pathway,p_ms3=pval)], by="pathway", all=TRUE)
cat("\n=== Table Y 実体: minSize 1/2/3 での p 値比較 ===\n")
print(cmp[order(p_ms1)])
fwrite(cmp,"output/TableY_minsize_sensitivity.tsv",sep="\t")
cat("\nMGAT3 が全 minSize で有意か:\n"); print(cmp[pathway=="MGAT3"])
