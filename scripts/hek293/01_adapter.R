# Huang 2021 HEK293 KO N-glycan panel → 7 glycomeRes RDS (one per KO).
#
# - 1 xlsx row = 1 quant observation = 1 glycomeRes `group`
# - N curated Structure IDs (GlyTouCan) per row → N glycomeRes rows with
#   the same group/logFC, different toposeq (Kizuka manual_structures pattern;
#   step3_build_pk.R OR rule collapses at enzyme level)
# - Ambiguous_skip (build_tree_wurcs returns ambiguous=TRUE) are dropped from
#   the candidate set. A row with all candidates ambiguous → no glycomeRes
#   row (group absent).
# Run from the repository root.

suppressMessages({
  library(readxl); library(dplyr); library(tibble); library(stringr); library(igraph)
})
source("R/utils_formatting.R")
source("R/expand_wurcs_ambiguous.R")

`%||%` <- function(x, y) if (is.null(x)) y else x

XLSX     <- "data/Huang_2021/NIHMS1683936-supplement-5.xlsx"
CACHE_RDS <- "cache/hek293/gtc_to_wurcs.rds"
OUT_DIR  <- "output/hek293"
EPS      <- 1e-3   # match Kizuka step2_glycome.R convention
dir.create(OUT_DIR, recursive = TRUE, showWarnings = FALSE)

# ---------- read Table_S4_1 ----------
# Table_S4_1 contains THREE sections stacked in one sheet:
#   1. N-glycans  (rows ~2..42 of raw, after 2-row multi-header)
#   2. O-glycans  (starts ~row 44 with section header "O-glycans"/"Structural name")
#   3. GSLs       (starts ~row 61 with section header "GSLs"/"Structural name")
# The row-number column (col 1) restarts at 1 in each section, so we must
# anchor on the section break (first NA rownum row that separates sections)
# rather than trust the integer range.
raw <- suppressMessages(read_excel(XLSX, sheet = "Table_S4_1",
                                   skip = 2, col_names = FALSE))

sample_names <- c("WT", "MGAT1-KO", "MGAT2-KO", "MGAT4A&4B-KO", "MGAT5-KO",
                  "T-KO(MANA1&A2&B1)", "B4GALNT3&4-KO", "SLC35C1-KO")
# metadata cols 1..5; sample s (1..8) occupies cols 6..9, 10..13, ...
# Average is the 3rd sub-col, so index = 5 + (s-1)*4 + 3 = 4*s + 4
sample_avg_idx <- 4 * seq_along(sample_names) + 4
names(sample_avg_idx) <- sample_names

# Find the N-glycan section: starts at first row with integer-coercible rownum,
# ends at first NA rownum row after that.
rn <- suppressWarnings(as.integer(raw[[1]]))
nglyc_start <- which(!is.na(rn))[1]
# Find first NA-rownum row strictly after nglyc_start
gap_after_start <- which(is.na(rn) & seq_along(rn) > nglyc_start)
nglyc_end <- if (length(gap_after_start) > 0) gap_after_start[1] - 1 else length(rn)

cat(sprintf("N-glycan section: raw rows %d..%d (%d rows)\n",
            nglyc_start, nglyc_end, nglyc_end - nglyc_start + 1))

raw_n <- raw[nglyc_start:nglyc_end, ]
dat <- tibble(
  rownum     = as.integer(raw_n[[1]]),
  name       = as.character(raw_n[[2]]),
  struct_id  = as.character(raw_n[[5]])
)
for (s in sample_names) {
  dat[[paste0("avg_", s)]] <- as.numeric(raw_n[[ sample_avg_idx[s] ]])
}

# Drop rows where struct_id is "N/A" (no Structure ID assigned by Huang) so
# the candidate-set will be empty for those rows downstream.
cat(sprintf("Rows with struct_id == \"N/A\": %d\n",
            sum(dat$struct_id == "N/A", na.rm = TRUE)))

# ---------- expand Structure ID → toposeq candidates ----------
cache <- readRDS(CACHE_RDS)   # named list/vec: GlyTouCan → WURCS (NA on fail)

# For each GlyTouCan ID, return the SET of toposeqs implied by its WURCS.
# - Non-ambiguous WURCS: a single toposeq (same behaviour as the prior
#   build_tree_wurcs pipeline).
# - Ambiguous WURCS (`|` LIN with multi-parent alternatives): the full set
#   of biologically plausible topology candidates, generated by enumerating
#   all alternatives and canonicalising. Equivalent to Kizuka's
#   manual_structures expansion but auto-derived from the curated GlyTouCan
#   accession.
convert_one <- function(w) {
  if (is.na(w) || !nzchar(w)) return(character(0))
  expand_wurcs_to_toposeq(w)
}

# Build a GlyTouCan → toposeq-set map once
all_ids <- unique(trimws(unlist(strsplit(dat$struct_id, ";"))))
all_ids <- all_ids[grepl("^G[A-Z0-9]{7}$", all_ids)]
cat(sprintf("Unique GlyTouCan IDs: %d\n", length(all_ids)))

gtc_to_toposeq_set <- lapply(all_ids, function(id) convert_one(cache[[id]]))
names(gtc_to_toposeq_set) <- all_ids

n_ok       <- sum(lengths(gtc_to_toposeq_set) > 0)
n_extra    <- sum(lengths(gtc_to_toposeq_set) - 1L)
cat(sprintf("toposeq sets ok: %d / %d (%.1f%%);  extra toposeqs from |-expansion: %d\n",
            n_ok, length(all_ids),
            100 * n_ok / length(all_ids), max(0L, n_extra)))

# Per row: candidate toposeq set = union across the row's Structure IDs.
dat$candidates <- lapply(strsplit(dat$struct_id, ";"), function(ids) {
  ids <- trimws(ids)
  ids <- ids[ids %in% names(gtc_to_toposeq_set)]
  ts  <- unique(unlist(gtc_to_toposeq_set[ids], use.names = FALSE))
  ts[!is.na(ts) & nzchar(ts)]
})
dat$n_cand <- lengths(dat$candidates)
n_rows_lost <- sum(dat$n_cand == 0)
cat(sprintf("Rows with ≥1 candidate toposeq: %d / %d (lost %d)\n",
            sum(dat$n_cand > 0), nrow(dat), n_rows_lost))
if (n_rows_lost > 0) {
  cat("Lost row names (all-ambiguous):\n")
  print(dat$name[dat$n_cand == 0])
}

# ---------- build per-KO glycomeRes ----------
ko_conditions <- sample_names[sample_names != "WT"]
wt_avg <- dat$`avg_WT`

slug <- function(s) gsub("[^A-Za-z0-9]+", "_", s)

for (ko in ko_conditions) {
  ko_avg <- dat[[paste0("avg_", ko)]]
  logfc  <- log2((ko_avg + EPS) / (wt_avg + EPS))

  # Long-format expansion: one row per (xlsx row, candidate toposeq).
  rows <- lapply(seq_len(nrow(dat)), function(i) {
    cands <- dat$candidates[[i]]
    if (length(cands) == 0) return(NULL)
    tibble(
      glycanComp = dat$name[i],
      toposeq    = cands,
      diff       = paste0(ko, "_vs_WT"),
      group      = as.character(dat$rownum[i]),
      logFC      = logfc[i]
    )
  })
  gly <- bind_rows(rows) |> distinct(group, toposeq, .keep_all = TRUE)

  # Keep only finite logFC (drop rows where WT or KO Average is NA)
  gly <- gly |> filter(is.finite(logFC))

  out <- file.path(OUT_DIR, sprintf("glycomeRes_%s.rds", slug(ko)))
  saveRDS(gly, out)
  cat(sprintf("  %s: %d rows, %d unique groups, %d unique toposeq → %s\n",
              ko, nrow(gly),
              length(unique(gly$group)),
              length(unique(gly$toposeq)),
              out))
}

# Also save the per-row metadata for downstream debugging.
saveRDS(dat |> select(-candidates) |>
          mutate(candidates = sapply(dat$candidates, paste, collapse = ";"),
                 n_cand = lengths(dat$candidates)),
        file.path(OUT_DIR, "rowmeta.rds"))

cat("\nDone.\n")
